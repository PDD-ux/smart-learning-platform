"""Generate a template-isolated, camera-style synthetic holdout set.

This set is intentionally generated by a different rendering pipeline from the
training baseline: each sample is photographed onto a textured surface or inside
a display bezel, with independent scale, rotation, lighting and blur. It remains
synthetic and therefore does not replace a real-photo acceptance set.
"""

from __future__ import annotations

import argparse
import csv
import random
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_synthetic_classifier_dataset import GENERATORS, HEIGHT, LABELS, WIDTH  # noqa: E402


SCREEN_LABELS = {"代码", "PPT", "纯语音"}


def _textured_background(rng: random.Random) -> Image.Image:
    start = tuple(rng.randint(45, 205) for _ in range(3))
    end = tuple(max(20, min(235, value + rng.randint(-55, 55))) for value in start)
    image = Image.new("RGB", (WIDTH, HEIGHT))
    draw = ImageDraw.Draw(image)
    for y in range(HEIGHT):
        ratio = y / max(1, HEIGHT - 1)
        color = tuple(int(a * (1.0 - ratio) + b * ratio) for a, b in zip(start, end))
        draw.line((0, y, WIDTH, y), fill=color)
    for _ in range(1_800):
        x, y = rng.randrange(WIDTH), rng.randrange(HEIGHT)
        shade = rng.randint(-22, 22)
        pixel = image.getpixel((x, y))
        image.putpixel((x, y), tuple(max(0, min(255, value + shade)) for value in pixel))
    return image.filter(ImageFilter.GaussianBlur(radius=0.35))


def _place_capture(base: Image.Image, label: str, rng: random.Random) -> Image.Image:
    canvas = _textured_background(rng).convert("RGBA")
    scale = rng.uniform(0.63, 0.86)
    content = base.resize((int(WIDTH * scale), int(HEIGHT * scale)), Image.Resampling.LANCZOS)

    if label in SCREEN_LABELS:
        bezel = rng.randint(10, 24)
        framed = Image.new(
            "RGBA",
            (content.width + bezel * 2, content.height + bezel * 2 + rng.randint(8, 24)),
            (15, 18, 23, 255),
        )
        framed.alpha_composite(content.convert("RGBA"), (bezel, bezel))
        content = framed
    elif label != "other":
        border = rng.randint(5, 14)
        framed = Image.new(
            "RGBA",
            (content.width + border * 2, content.height + border * 2),
            (236, 232, 222, 255),
        )
        framed.alpha_composite(content.convert("RGBA"), (border, border))
        content = framed

    content = content.convert("RGBA")
    angle = rng.uniform(-11.0, 11.0)
    content = content.rotate(
        angle,
        resample=Image.Resampling.BICUBIC,
        expand=True,
        fillcolor=(0, 0, 0, 0),
    )
    max_x = max(0, WIDTH - content.width)
    max_y = max(0, HEIGHT - content.height)
    x = rng.randint(0, max_x) if max_x else 0
    y = rng.randint(0, max_y) if max_y else 0

    shadow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    alpha = content.getchannel("A")
    shadow_shape = Image.new("RGBA", content.size, (0, 0, 0, rng.randint(95, 150)))
    shadow_shape.putalpha(alpha)
    shadow.alpha_composite(shadow_shape, (min(WIDTH - 1, x + 12), min(HEIGHT - 1, y + 14)))
    shadow = shadow.filter(ImageFilter.GaussianBlur(radius=rng.uniform(7.0, 13.0)))
    canvas = Image.alpha_composite(canvas, shadow)
    canvas.alpha_composite(content, (x, y))

    result = canvas.convert("RGB")
    result = ImageEnhance.Brightness(result).enhance(rng.uniform(0.72, 1.18))
    result = ImageEnhance.Contrast(result).enhance(rng.uniform(0.78, 1.22))
    if rng.random() < 0.7:
        result = result.filter(ImageFilter.GaussianBlur(radius=rng.uniform(0.25, 1.35)))
    return result


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="生成模板隔离的八分类拍摄风格测试集")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "dataset" / "classifier-holdout",
    )
    parser.add_argument("--per-class", type=int, default=20)
    parser.add_argument("--seed", type=int, default=20260920)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.per_class < 1:
        raise ValueError("per-class 必须大于 0")
    existing = list(args.output.glob("*/*.jpg"))
    if existing:
        raise RuntimeError(f"输出目录已有 {len(existing)} 张 JPG，拒绝覆盖：{args.output}")

    rows: list[dict[str, str]] = []
    for label_index, label in enumerate(LABELS):
        for item_index in range(args.per_class):
            rng = random.Random(args.seed + label_index * 100_000 + item_index)
            base = GENERATORS[label](rng).convert("RGB")
            image = _place_capture(base, label, rng)
            destination = args.output / label / f"holdout_{item_index:04d}.jpg"
            destination.parent.mkdir(parents=True, exist_ok=True)
            image.save(destination, "JPEG", quality=rng.randint(72, 90), optimize=True)
            rows.append(
                {
                    "relative_path": destination.relative_to(args.output.parent).as_posix(),
                    "split": "holdout",
                    "task": "classifier",
                    "label": label,
                    "source_url": "generated-locally",
                    "license_or_permission": "project-generated synthetic data; no third-party assets",
                    "contains_personal_data": "no",
                    "review_status": "camera-style-holdout",
                    "notes": f"seed={args.seed}; generator=camera-holdout-v1",
                }
            )

    manifest = args.output / "holdout-manifest.csv"
    with manifest.open("w", newline="", encoding="utf-8-sig") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"generated {len(rows)} holdout images in {args.output}")


if __name__ == "__main__":
    main()
