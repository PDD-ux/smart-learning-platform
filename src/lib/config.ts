/**
 * 全局可调参数集中管理。
 *
 * 这些数字原本散落在各处：一个超时写在调用的那一行的匿名数字里，
 * 分页大小直接拼在 URL 字符串里，模型默认温度藏在请求体构造的中途。
 * 要调一个值得翻好几个文件，还容易漏改同位的值。集中到这里之后，
 * 调参、对齐前后端、按环境微调都只动这一个文件。
 *
 * 收录范围：跨场景复用的通用参数。
 * 不收录：某个调用点为自己的场景专门调的值（例如忠实性审查固定用
 * temperature: 0 保证判定稳定）。那种值留在原地反而更好读，
 * 抽到全局会让调用点丢失「这里为什么是这个数」的上下文。
 *
 * 所有数值保持与抽取前完全一致，本模块只做归集，不改变任何运行行为。
 */

